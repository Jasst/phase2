# -*- coding: utf-8 -*-
"""Все гиперпараметры в одном месте. Сохраняются вместе с состоянием сети."""
from dataclasses import dataclass


@dataclass
class Config:
    # нейроны и ансамбли (кластеры)
    dim: int = 48                   # размерность векторов нейрона
    max_clusters: int = 1024        # ёмкость ансамблей (слотов цепи)
    merge_sim: float = 0.5          # косинус профилей соседей, с которого нейроны объединяются
    max_cluster_size: int = 12      # ансамбль не разрастается дальше этого размера
    max_merges_per_lesson: int = 3  # за один урок не больше стольких слияний: сеть развивается постепенно
    # совместная встреча слов (ближайшие соседи сближаются)
    emb_window: int = 3
    emb_negatives: int = 3
    lr_sgns: float = 0.05
    lr_emb: float = 0.05
    # дистилляция в выходную голову
    lr_out: float = 0.4
    smooth: float = 0.05            # сглаживание мягкой цели учителя
    alpha: float = 0.4              # доля ансамблевого контекста (импульс) в контексте шага
    beta: float = 0.3               # доля вопроса в контексте каждого шага: импульс не забывает, о чём спросили
    # направленные цепи импульсов
    chain_window: int = 3
    chain_link: float = 1.0         # сила связи «вопрос → начало ответа»
    chain_forget: float = 0.002     # забывание связей за один урок
    chain_topk: int = 4             # конкуренция: сколько ансамблей проходит импульс
    anchor_mix: float = 0.2         # подмешивание вопроса, чтобы цепь не уходила в сторону
    visited_decay: float = 0.5      # рефрактерность: затухание памяти о пройденных ансамблях
    # генерация
    max_answer: int = 24
    temperature: float = 0.6
    rep_penalty: float = 1.5
    ensemble_gain: float = 1.0      # слово получает бонус, если его ансамбль активен в импульсе
    no_repeat: int = 30             # слово не повторяется в пределах последних N шагов ответа
    freq_penalty: float = 0.2       # штраф за частоту слова: contrastive-поправка на log(частота)
    # повторение опыта (против забывания)
    replay_size: int = 300
    replay_n: int = 2
    replay_weight: float = 0.3
    pretrain_epochs: int = 4
    # мысль: непрерывность между ходами и фокус
    focus_gain: float = 0.6         # доля вопроса в новой мысли (остальное — прошлая мысль)
    thought_decay: float = 0.5      # как сильно ответ переписывает мысль (0 — не меняет, 1 — полностью)
    settle_steps: int = 2           # внутренние шаги импульса до ответа (мысль устаканивается)
    min_confidence: float = 0.02    # ниже этой массы сеть честно говорит, что не уверена
    # поток мыслей (внутренний нарратив)
    thought_mix: float = 0.3        # доля последних мыслей в якоре вопроса: нарратив участвует в ответе
    thought_weight: float = 0.5     # вес урока «из контекста мыслей следует следующая мысль»
    # цепочки слов (память порядка): какое слово шло за которым в уроках
    trans_gain: float = 2.0         # вес цепочек: слово, которое в уроках следовало за текущим, получает бонус
    trans_tri_w: float = 0.7        # доля триграммы (два предыдущих слова) в смеси с биграммой
    trans_floor: float = 1e-3       # сглаживание: слово без продолжения в уроках почти не выбирается
    # слепки мыслей и проактивный режим
    imprint_batch: int = 10         # каждые N слепков — консолидация: дедупликация и конкатенация
    imprint_dedupe: float = 0.7     # Жаккар слов, с которого слепки считаются одной мыслью
    longterm_dedupe: float = 0.85   # долговременная память: цепочки сливаются только почти совпадающие
    imprint_cap: int = 64           # размер кратковременной памяти слепков
    imprint_decay: float = 0.05     # угасание неважных слепков за консолидацию
    protect_at: float = 0.5         # важность, с которой мысль защищена от забывания и вытеснения
    longterm_cap: int = 300         # долговременная память цепочек (вытеснение по важности)
    consolidate_weight: float = 0.3 # вес, с которым консолидированные мысли закрепляются в цепочках
    replay_protected: int = 2       # сколько защищённых мыслей повторяется при каждом уроке
    reason_steps: int = 3           # шагов проактивного рассуждения за ход
    reason_words: int = 10          # слов в одном импульсе мысли
    inhib_gain: float = 1.5         # торможение: недавно сказанное слово получает штраф
    inhib_decay: float = 0.6        # скорость угасания торможения за шаг
    cycle_penalty: float = 3.0      # синапс-запрет: повтор пройденной пары слов блокируется
    stop_gain: float = 2.0          # стоп-паттерн: конец фразы поощряется с ростом длины
    reason_cycle_sim: float = 0.9   # косинус слепков, с которого рассуждение считается петлёй
    align_start: bool = True        # согласование: генерация стартует из якоря вопроса, как обучение
    mmr_lambda: float = 0.6         # планировщик: баланс оценки и разнообразия вариантов (1 — только оценка)
    plan_rel: float = 2.0           # веса оценки вариантов (калибруются по набору проверки)
    plan_coh: float = 1.0
    plan_len_alpha: float = 0.7
    seed: int = 0
